export const getDoctorById = (id) =>
  doctors.find((doctor) => doctor.id === Number(id)) || null;

export const getSpecialtyCount = (specialty) =>
  doctors.filter((doctor) => doctor.specialty === specialty).length;

export const getCityCount = (city) =>
  doctors.filter((doctor) => doctor.city === city).length;

export const searchDoctors = ({ specialty, city, query, sort } = {}) => {
  const term = (query || '').trim().toLowerCase();
  const results = doctors.filter((doctor) => {
    if (specialty && doctor.specialty !== specialty) {
      return false;
    }
    if (city && doctor.city !== city) {
      return false;
    }
    if (term) {
      const haystack = [doctor.name, doctor.specialty, doctor.city, doctor.area]
        .join(' ')
        .toLowerCase();
      if (!haystack.includes(term)) {
        return false;
      }
    }
    return true;
  });

  if (sort === 'fee-low') {
    return results.sort((a, b) => a.visitCost - b.visitCost);
  }
  if (sort === 'fee-high') {
    return results.sort((a, b) => b.visitCost - a.visitCost);
  }
  if (sort === 'experience') {
    return results.sort((a, b) => b.experienceYears - a.experienceYears);
  }
  return results.sort((a, b) => b.rating - a.rating);
};

const byRatingThenExperience = (a, b) =>
  b.rating - a.rating ||
  b.experienceYears - a.experienceYears ||
  b.ratingCount - a.ratingCount;

export const topRatedDoctors = (limit = 4) =>
  [...doctors].sort(byRatingThenExperience).slice(0, limit);

export const getFeaturedDoctor = () =>
  [...doctors].sort(byRatingThenExperience)[0] || null;

